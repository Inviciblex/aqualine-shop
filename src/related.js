// Подбор сопутствующих товаров («С этим покупают»).
//
// Два источника, по приоритету:
//  1) ручной список product.related — массив id товаров (задаётся в каталоге
//     колонкой `related`: id через вертикальную черту, напр. «3|7|10»);
//  2) если ручной список не задан — эвристика по «дополняющим» категориям
//     (к раковине — смеситель и т.п.). Сначала товары в наличии.
//
// Это кросс-категорийные дополнения, в отличие от блока «Похожие товары»
// (товары той же категории).

// Какие категории дополняют друг друга при покупке.
const COMPLEMENTS = {
  Смесители: ['Раковины', 'Душевые системы'],
  Раковины: ['Смесители', 'Трубы и фитинги'],
  Унитазы: ['Трубы и фитинги', 'Раковины'],
  'Душевые системы': ['Смесители', 'Полотенцесушители'],
  Ванны: ['Смесители', 'Душевые системы'],
  Полотенцесушители: ['Трубы и фитинги'],
  Водонагреватели: ['Смесители', 'Трубы и фитинги'],
  'Трубы и фитинги': ['Смесители'],
}

export function relatedProducts(product, all = [], limit = 4) {
  if (!product) return []
  const others = all.filter((p) => p && p.id !== product.id)

  // 1) Ручной список related (по id, в заданном порядке, только существующие).
  if (Array.isArray(product.related) && product.related.length) {
    const byId = new Map(others.map((p) => [p.id, p]))
    return product.related
      .map((id) => byId.get(id))
      .filter(Boolean)
      .slice(0, limit)
  }

  // 2) Эвристика: товары из дополняющих категорий, сначала в наличии.
  const cats = COMPLEMENTS[product.category] || []
  if (!cats.length) return []
  const pool = others.filter((p) => cats.includes(p.category))
  // Стабильная сортировка: в наличии — выше, исходный порядок сохраняется.
  return pool
    .map((p, i) => ({ p, i }))
    .sort((a, b) => Number(b.p.inStock) - Number(a.p.inStock) || a.i - b.i)
    .map(({ p }) => p)
    .slice(0, limit)
}
